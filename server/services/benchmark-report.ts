import type { BenchmarkResult } from '../../shared/types/lab'
import { DASH, bytes, card, compact, date, esc, htmlDocument, kpi, kv, lineChart, ms, num, table } from './report-html'

// Self-contained HTML report for one benchmark run: same content as the Run card in the UI
// (KPIs, timeline charts, configuration, environment, data size, indexes, plan, errors).

export function benchmarkHtml(r: BenchmarkResult, job: { id: string; title: string; status: string }): string {
  const env = r.environment
  const total = r.operations + r.errors
  const errRate = total ? (r.errors / total) * 100 : 0
  const heading = `#${r.scenario.no} ${r.scenario.name} · ${r.config.concurrency} session(s) · ${r.config.durationSeconds}s`

  const config: [string, string][] = [
    ['Scenario', `#${r.scenario.no} ${r.scenario.name} (${r.scenario.category})`],
    ['Description', r.scenario.description],
    ['Label', r.config.label || DASH],
    ['Sessions', `${r.config.concurrency} · warm-up ${r.config.warmupSeconds} s · duration ${r.config.durationSeconds} s · think ${r.config.thinkTimeMs} ms`],
    ['Batch / ratio', `batch ${r.config.batchSize} · read ratio ${r.config.readRatio}`],
    ['Target', `${r.config.schema}.${r.config.prefix}*`],
    ['Oracle', `${env.banner || env.oracleVersion} · ${env.edition}`],
    ['Instance', `${env.instanceName ?? DASH}${env.isRac ? ' (RAC)' : ''}`],
    ['DB host', `${env.dbCpuCount != null ? `${env.dbCpuCount} CPUs` : 'CPUs n/a'} · ${env.dbPhysicalMemoryBytes != null ? bytes(env.dbPhysicalMemoryBytes) : 'memory n/a'}`],
    ['App host', `${env.appHost.cpus}× ${env.appHost.cpuModel} · ${bytes(env.appHost.totalMemBytes)} · ${env.appHost.platform} · Node ${env.appHost.node}`],
    ['Driver', `node-oracledb ${env.driverMode} mode`],
    ['Window', `${date(r.startedAt)} → ${date(r.finishedAt)} (measured ${num(r.measuredSeconds, 1)} s)`],
    ['Job', job.id],
  ]

  const throughput = lineChart({ name: 'ops/s', color: 'var(--chart-1)', area: true, points: r.timeline.map((t) => ({ x: t.t, y: t.ops })), yFormat: compact })
  const p95 = lineChart({ name: 'p95', color: 'var(--chart-2)', area: false, points: r.timeline.map((t) => ({ x: t.t, y: t.p95Ms })), yFormat: ms })

  const body = `
  <section class="card">
    <div class="card-body head">
      <span class="badge${job.status === 'succeeded' ? '' : ' bad'}">${esc(job.status)}</span>
      <h1>${esc(heading)}</h1>
      <div class="meta">${r.config.label ? `${esc(r.config.label)} · ` : ''}${esc(r.config.schema)}.${esc(r.config.prefix)}* · ${esc(date(r.startedAt))} · ${esc(env.oracleVersion)}${env.instanceName ? ` · ${esc(env.instanceName)}` : ''}</div>
    </div>
  </section>

  <div class="grid kpis">
    ${kpi('Throughput', `${num(r.opsPerSec, 1)} ops/s`, `${num(r.operations)} ops in ${num(r.measuredSeconds, 1)} s`, 'info')}
    ${kpi('Rows / s', num(r.rowsPerSec, 1), `${num(r.rows)} rows`)}
    ${kpi('Latency p50', ms(r.latency.p50Ms), `avg ${ms(r.latency.avgMs)}`)}
    ${kpi('Latency p95', ms(r.latency.p95Ms), `min ${ms(r.latency.minMs)}`)}
    ${kpi('Latency p99', ms(r.latency.p99Ms), `max ${ms(r.latency.maxMs)}`)}
    ${kpi('Errors', num(r.errors), `${errRate.toFixed(2)}% · ${r.timeouts} timeouts`, r.errors ? 'bad' : 'ok')}
  </div>

  <div class="grid two">
    ${card('Throughput per second', throughput)}
    ${card('p95 latency per second', p95)}
  </div>

  <div class="grid two">
    ${card('Run configuration & environment', kv(config))}
    ${card(
      'Data size & indexes at run time',
      table(['Table', 'Rows (stats)'], env.dataSize.map((d) => [d.table, d.rows == null ? 'no stats' : num(d.rows)]), [1]) +
        table(['Table', 'Index', 'Columns'], env.indexes.map((x) => [x.table, x.index, x.columns])),
      { flush: true },
    )}
  </div>

  ${r.plan ? card('Execution plan', `<pre>${esc(r.plan)}</pre>`) : ''}
  ${r.errorSamples.length ? card('Error samples', `<ul class="errs">${r.errorSamples.map((e) => `<li>${esc(e)}</li>`).join('')}</ul>`) : ''}

  ${card('Timeline', table(['t (s)', 'ops', 'p95', 'errors'], r.timeline.map((t) => [num(t.t, 1), num(t.ops), ms(t.p95Ms), num(t.errors)]), [0, 1, 2, 3]), { flush: true })}
`
  return htmlDocument(
    `Benchmark report · ${r.scenario.name}`,
    body,
    `Generated by OracleDB Data Lab · ${new Date().toISOString()} · latencies are client-observed round trips, warm-up excluded`,
  )
}
