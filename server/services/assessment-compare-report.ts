import type { AssessmentDiff, AssessmentSnapshotMeta, FindingChange, PanelDiff } from '../../shared/types/lab'
import { DASH, bytes, card, date, esc, htmlDocument, kpi, kv, num, table } from './report-html'

// Standalone HTML report of a snapshot comparison (A → B): identity, counts, health-check movement
// and per-area configuration changes. Same look as the other reports.

const SEV = { critical: 'bad', warning: 'warn', info: 'info', ok: '', na: 'na' } as const

function who(m: AssessmentSnapshotMeta) {
  return `${m.dbName ?? m.profileName}${m.container && m.container !== m.dbName ? ` / ${m.container}` : ''} · ${date(m.createdAt)}${m.label ? ` · ${m.label}` : ''}`
}

function cell(v: unknown, field = ''): string {
  if (v == null || v === '') return DASH
  if (typeof v === 'number') return /bytes/i.test(field) ? bytes(v) : num(v, 2)
  if (typeof v === 'object') return JSON.stringify(v)
  return String(v)
}

function badge(s: string | null) {
  return s ? `<span class="badge ${SEV[s as keyof typeof SEV] ?? ''}">${esc(s)}</span>` : DASH
}

function findingsTable(title: string, list: FindingChange[]) {
  if (!list.length) return ''
  const rows = list
    .map((f) => `<tr><td>${badge(f.a)}</td><td>${badge(f.b)}</td><td><strong>${esc(f.title)}</strong> <span class="muted">${esc(f.category)}</span><br>${esc(f.detailB ?? f.detailA ?? '')}</td></tr>`)
    .join('')
  return card(`${title} · ${list.length}`, `<div class="table-wrap"><table><thead><tr><th>A</th><th>B</th><th>Check</th></tr></thead><tbody>${rows}</tbody></table></div>`, { flush: true })
}

function rowSummary(r: Record<string, unknown>) {
  return Object.entries(r)
    .filter(([, v]) => v != null && v !== '' && typeof v !== 'object')
    .slice(0, 5)
    .map(([k, v]) => `${k}=${cell(v, k)}`)
    .join(' · ')
}

function panelBlock(p: PanelDiff) {
  if (p.status !== 'ok') return card(p.title, `<p class="note">Not comparable — ${esc(p.note ?? '')}</p>`, { flush: true })
  const parts: string[] = []
  if (p.added.length) parts.push(table(['Added in B', 'Details'], p.added.map((x) => [x.key, rowSummary(x.row)])))
  if (p.removed.length) parts.push(table(['Removed (only in A)', 'Details'], p.removed.map((x) => [x.key, rowSummary(x.row)])))
  if (p.changed.length) parts.push(table(['Changed', 'Field', 'A', 'B'], p.changed.flatMap((c) => c.changes.map((ch) => [c.key, ch.field, cell(ch.a, ch.field), cell(ch.b, ch.field)]))))
  if (p.numeric.length) parts.push(table(['Drift', 'Metric', 'A', 'B', 'Δ'], p.numeric.map((n) => [n.key, n.field, cell(n.a, n.field), cell(n.b, n.field), n.delta == null ? DASH : `${n.delta > 0 ? '+' : ''}${cell(n.delta, n.field)}`]), [2, 3, 4]))
  const head = `${p.title} · +${p.added.length} −${p.removed.length} ~${p.changed.length}`
  return card(head, parts.join('') + `<p class="note">${p.unchanged} unchanged.</p>`, { flush: true })
}

export function compareHtml(d: AssessmentDiff): string {
  const f = d.findings
  const changedPanels = d.panels.filter((p) => p.status !== 'ok' || p.added.length || p.removed.length || p.changed.length || p.numeric.length)
  const quiet = d.panels.filter((p) => !changedPanels.includes(p)).map((p) => p.title)
  const body = `
  <section class="card"><div class="card-body head">
    <h1>Assessment comparison</h1>
    <div class="meta">A: ${esc(who(d.a))}<br>B: ${esc(who(d.b))}</div>
  </div></section>
  <div class="grid kpis">
    ${kpi('New / worse issues', String(f.appeared.length + f.worse.length), 'health checks that got worse', f.appeared.length + f.worse.length ? 'bad' : 'ok')}
    ${kpi('Resolved / better', String(f.resolved.length + f.better.length), 'health checks that improved', 'ok')}
    ${kpi('Still open', String(f.stillOpen.length), 'unchanged issues', f.stillOpen.length ? 'warn' : 'ok')}
    ${kpi('Config changes', String(d.totals.changed), `+${d.totals.added} added · −${d.totals.removed} removed`, 'info')}
  </div>
  ${d.identity.length ? card('Identity changes', table(['Field', 'A', 'B'], d.identity.map((i) => [i.field, cell(i.a), cell(i.b)])), { flush: true }) : ''}
  ${d.counts.length ? card('Inventory counts', table(['Metric', 'A', 'B', 'Δ'], d.counts.map((c) => [c.key, cell(c.a, c.key), cell(c.b, c.key), c.delta == null ? DASH : `${c.delta > 0 ? '+' : ''}${cell(c.delta, c.key)}`]), [1, 2, 3]), { flush: true }) : ''}
  ${findingsTable('New issues', f.appeared)}
  ${findingsTable('Got worse', f.worse)}
  ${findingsTable('Resolved', f.resolved)}
  ${findingsTable('Improved', f.better)}
  ${findingsTable('Still open', f.stillOpen)}
  <h3>Configuration & inventory changes</h3>
  ${changedPanels.map(panelBlock).join('\n')}
  ${quiet.length ? card('No differences', kv([['Areas', quiet.join(', ')]])) : ''}
`
  return htmlDocument(`Assessment comparison · ${d.a.dbName ?? d.a.profileName} → ${d.b.dbName ?? d.b.profileName}`, body, `Generated by OracleDB Data Lab · ${new Date().toISOString()}`)
}
